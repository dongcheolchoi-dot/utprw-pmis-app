  let currentLang = 'ko';
  try {
    const saved = localStorage.getItem(global.PMIS_CONFIG.STORAGE_KEYS.LANG);
    if (saved && DICT[saved]) currentLang = saved;
  } catch (e) {}

  function t(key) {
    const table = DICT[currentLang] || DICT.ko;
    return (table[key] !== undefined) ? table[key] : (DICT.en[key] !== undefined ? DICT.en[key] : key);
  }

  function tf(key, params) {
    let str = t(key);
    if (params && typeof params === 'object') {
      Object.keys(params).forEach((k) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(params[k] == null ? '' : params[k]));
      });
    }
    return str;
  }

  function setLang(lang) {
    if (!DICT[lang]) return;
    currentLang = lang;
    try { localStorage.setItem(global.PMIS_CONFIG.STORAGE_KEYS.LANG, lang); } catch (e) {}
    applyI18nToDom();
  }

  function getLang() {
    return currentLang;
  }

  function applyI18nToDom() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    document.querySelectorAll('.lang-pill-btn').forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
    });
  }

  function translateStatus(rawStatus) {
    const s = String(rawStatus || '').trim();
    const u = s.toUpperCase();
    if (!s) return t('status_pending');
    if (u === 'CLOSED' || s.indexOf('종결') !== -1 && s.indexOf('미입력') === -1) return t('status_closed');
    if (u === 'CLOSED_COPY_MISSING' || s.indexOf('미입력') !== -1) return t('status_closed_missing');
    if (u === 'INSP_DONE' || s.indexOf('검측 완료') !== -1 || s.indexOf('✅') !== -1) return t('status_insp_done');
    if (u === 'INSP_ASSIGNED' || s.indexOf('검측원 배정') !== -1) return t('status_insp_assigned');
    if (u === 'REVIEW_DONE' || s.indexOf('검토 완료') !== -1) return t('status_review_done');
    if (u === 'UNDER_REVIEW' || s.indexOf('담당자 검토') !== -1) return t('status_under_review');
    if (u === 'ASSIGNED' || s.indexOf('배정') !== -1) return t('status_assigned');
    if (u === 'RECEIVED' || s.indexOf('접수') !== -1) return t('status_received');
    if (u === 'REJECTED' || s.indexOf('반려') !== -1) return t('status_rejected');
    if (u === 'CANCELED' || s.indexOf('취소') !== -1) return t('status_canceled');
    return s;
  }

  global.PMIS_I18N = { t, tf, setLang, getLang, applyI18nToDom, translateStatus };
